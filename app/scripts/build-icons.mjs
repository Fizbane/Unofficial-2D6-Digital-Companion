// Build public/icons.svg: a sprite of only the Lucide icons the UI uses (run before dev/build).
// Keep NAMES in step with ICON_NAMES in src/ui/icon.ts (test/icons.test.ts checks the sprite).
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "book", "swords", "key", "castle", "scroll", "settings", "search", "star", "star-filled",
  "map", "notebook", "user", "dice", "rotate-ccw", "plus", "x", "chevron-left", "chevron-right",
  "chevron-down", "panel-left", "panel-right", "palette", "image", "external-link", "pencil",
  "more-horizontal", "file-text", "trash", "download", "upload", "minus", "menu", "check",
  "shield", "skull", "trophy", "crosshair", "zap", "heart", "door-closed", "utensils", "arrow-down", "circle-x", "key-round",
  "arrow-up", "arrow-left-right", "compass", "calendar", "flag", "coins", "hammer", "landmark", "backpack", "wand-sparkles", "sun-moon", "type", "layout-grid", "crown", "droplet", "triangle-alert", "sparkles", "book-open", "gem", "hard-hat",
  "skip-back", "skip-forward", "pause", "play", "house", "grip-vertical", "table", "chart-column",
];

// Our name -> lucide-static file name, where they differ.
const SOURCE = { "star-filled": "star", dice: "dice-5" };
// Icons drawn filled rather than outlined.
const FILLED = new Set(["star-filled"]);

const symbols = NAMES.map((name) => {
  const file = `node_modules/lucide-static/icons/${SOURCE[name] ?? name}.svg`;
  const svg = readFileSync(file, "utf8");
  const inner = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/)?.[1];
  if (!inner) throw new Error(`build-icons: cannot parse ${file}`);
  const body = inner.replace(/\s*\n\s*/g, "").trim();
  const fill = FILLED.has(name) ? "currentColor" : "none";
  return `<symbol id="i-${name}" viewBox="0 0 24 24" fill="${fill}" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`;
});

const out =
  `<!-- Generated by scripts/build-icons.mjs from lucide-static (ISC). Do not edit. -->\n` +
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join("\n")}\n</svg>\n`;
writeFileSync("public/icons.svg", out);
console.log(`icons.svg written (${NAMES.length} icons)`);
