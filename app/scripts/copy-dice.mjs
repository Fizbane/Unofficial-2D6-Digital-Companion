// Copy 3D dice engine assets + dice skins into public/ (run automatically before dev/build).
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

import { createCanvas, loadImage } from "@napi-rs/canvas";

const dest = "public/assets/dice-box";
rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
cpSync("node_modules/@3d-dice/dice-box/dist/assets", dest, { recursive: true });

// Built-in skins from @3d-dice/dice-themes (MIT)
const builtIn = ["default", "gemstone", "gemstoneMarble", "blueGreenMetal", "rust", "rock", "wooden", "smooth", "smooth-pip", "diceOfRolling"];
for (const t of builtIn) cpSync(`node_modules/@3d-dice/dice-themes/themes/${t}`, `${dest}/themes/${t}`, { recursive: true });

// Custom skins generated by pipeline/make_dice_themes.py
if (existsSync("dice-themes")) cpSync("dice-themes", `${dest}/themes`, { recursive: true });

// The animated pair uses the same numbered faces and collider as Smooth Pips.
const celestialPips = await loadImage(`${dest}/themes/smooth-pip/pips-light.png`);
for (const [id, name, tint] of [
  ["sunCore", "Sun", "rgba(228, 129, 27, 0.33)"],
  ["moonCore", "Moon", "rgba(89, 127, 220, 0.33)"],
]) {
  const folder = `${dest}/themes/${id}`;
  mkdirSync(folder);
  cpSync(`${dest}/themes/smooth-pip/smooth-pip.json`, `${folder}/smooth-pip.json`);
  const canvas = createCanvas(celestialPips.width, celestialPips.height);
  const ctx = canvas.getContext("2d");
  ctx.fillStyle = tint;
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.drawImage(celestialPips, 0, 0);
  writeFileSync(`${folder}/pips.png`, canvas.toBuffer("image/png"));
  writeFileSync(`${folder}/theme.config.json`, JSON.stringify({
    name, systemName: id, extends: "smooth", meshFile: "smooth-pip.json",
    material: { type: "standard", diffuseTexture: "pips.png" },
    diceAvailable: ["pip"],
  }));
}

// The pip-face dice meshes (smooth-pip and the custom skins) are about 15% smaller than the numbered d6 of the
// default set, so a pip die thrown beside a numbered one looked smaller. Scale the pip meshes (and their colliders)
// up to the numbered die's size. The copies are rebuilt from the sources above on every run, so this never compounds.
const NUMBERED_D6 = 0.1566, PIP = 0.1328; // edge lengths in mesh units, measured from default.json and smooth-pip.json
const k = NUMBERED_D6 / PIP;
for (const t of readdirSync(`${dest}/themes`)) {
  for (const f of readdirSync(`${dest}/themes/${t}`).filter((n) => n.endsWith("-pip.json"))) {
    const path = `${dest}/themes/${t}/${f}`;
    const mesh = JSON.parse(readFileSync(path, "utf8"));
    for (const m of mesh.meshes ?? []) if (/^pip/.test(m.id ?? m.name ?? "") && Array.isArray(m.positions)) m.positions = m.positions.map((v) => v * k);
    writeFileSync(path, JSON.stringify(mesh));
  }
}
console.log("dice assets copied");
